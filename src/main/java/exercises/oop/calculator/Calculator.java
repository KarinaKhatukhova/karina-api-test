package exercises.oop.calculator;

public class Calculator {

    public void multiply(int a, int b) {
        int result = a * b;
        System.out.println(result);
    }


    public void multiply(int a, double b) {
        double result = a * b;
        System.out.println(result);
    }


    public void multiply(double a, double b) {
        double result = a * b;
        System.out.println(result);
    }
}


